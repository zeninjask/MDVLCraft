"""12x12 silhouettes for the small twig bonuses (drawn as outlines at 1:1 in 12px twig nodes)."""

M = {}


def mini(name, art):
    rows = art.strip('\n').split('\n')
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), (name, [len(r) for r in rows])
    M[name] = [[c == '#' for c in r] for r in rows]


