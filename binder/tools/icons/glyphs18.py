"""18x18 icon silhouettes ('#' = filled). The Line style draws their 1px outline, so filled shapes read as hollow
outlines and 1-2px strokes stay as lines. Modifiers (7x7) mark what a bonus does to the base symbol."""

G = {}
MOD = {}


def glyph(name, art, size=18, table=G):
    rows = art.strip('\n').split('\n')
    assert len(rows) == size and all(len(r) == size for r in rows), (name, len(rows), [len(r) for r in rows])
    table[name] = [[c == '#' for c in r] for r in rows]


def mod(name, art):
    glyph(name, art, 7, MOD)


