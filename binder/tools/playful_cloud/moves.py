# ------------------------------------------------------------------------------------------------- strike helpers
CEN = {"R": (0.24, 0.55, 0.05), "L": (-0.24, 0.55, 0.05)}


def H(side, az, el, rad=0.45, aaz=None, ael=None):
    """One hand on a sphere round its shoulder at (az, el); its blade points to (aaz, ael), by default a little
    above the arm's line (a sword held out)."""
    return {side: add3(CEN[side], sph(az, el), rad),
            "a" + side: sph(az if aaz is None else aaz, el + 35 if ael is None else ael)}


def HH(r, l):
    return merge(H("R", *r), H("L", *l))


GUARD = HH((15, 5, 0.38, -20, 70), (-15, -5, 0.38, 20, 60))     # both blades up in front, ready
ST = {"fR": (0.18, 0, -0.08), "fL": (-0.18, 0, 0.18)}           # fighting stance, left foot forward
STR = {"fR": (0.18, 0, 0.18), "fL": (-0.18, 0, -0.08)}          # right foot forward


def k(t, *ds, **kw):
    d = merge(*ds); d.update(kw)
    return (t, d)


def strike(name, length, keys, hits):
    return Move(name, length, keys, hits=hits)


