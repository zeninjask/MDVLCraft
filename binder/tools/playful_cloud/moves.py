ALL = {}


def add(group, variant, *moves):
    ALL.setdefault(group, {})[variant] = list(moves)


def sph(az, el):
    """Unit vector: az degrees to the right of forward, el degrees up."""
    a, e = math.radians(az), math.radians(el)
    return (math.sin(a) * math.cos(e), math.sin(e), math.cos(a) * math.cos(e))


def add3(a, b, k=1.0):
    return tuple(x + y * k for x, y in zip(a, b))


SH_R = (0.22, 0.52, 0.05)          # swing centre a little inside the right shoulder


def W(az, el, rad=0.5, c=SH_R, lift=0.0):
    """Both hands on the right hand's end section, swung to (az, el)."""
    d = sph(az, el + lift)
    R = add3(c, sph(az, el), rad)
    return {"R": R, "aR": d, "L": add3(R, d, 0.13), "aL": d}


def O(az, el, rad=0.5, c=SH_R, L=(-0.32, 0.2, -0.2), aL=(0, -0.5, -1)):
    """Right hand only; the left hand is drawn back out of the staff's way."""
    R = add3(c, sph(az, el), rad)
    return {"R": R, "aR": sph(az, el), "L": L, "aL": aL}


def M(c, d, half=0.25):
    """Both hands on the middle section, centred on c, pointing along d (right hand first)."""
    n = np.array(d, float); n /= np.linalg.norm(n); n = tuple(n)
    return {"R": add3(c, n, -half), "L": add3(c, n, half), "aR": n, "aL": n}


def E(R, aR, L, aL):
    return {"R": R, "aR": aR, "L": L, "aL": aL}


def merge(*ds):
    out = {}
    for d in ds:
        out.update(d)
    return out


def gait(period, stride, lift, width=0.14, back_lift=None, phase=0.0):
    """Foot keys for a looping in-place gait (right foot lands forward at t = phase)."""
    back_lift = lift if back_lift is None else back_lift
    keys = []
    for side, off in (("fR", 0.0), ("fL", 0.5)):
        w = width if side == "fR" else -width
        for u, pos in ((0.0, (w, 0, stride)), (0.5, (w, 0, -stride)), (0.68, (w, back_lift, -stride * 0.5)),
                       (0.85, (w, lift, stride * 0.6))):
            t = ((u + off) * period + phase) % period
            keys.append((round(t, 4), {side: pos}))
    return keys


def cyc(period, n, fn):
    """n evenly spaced keys of a looping channel set: fn(phase in [0,1)) -> channels; the last repeats the first."""
    ks = [(period * i / n, fn(i / n)) for i in range(n)]
    ks.append((period, fn(0.0)))
    return ks


