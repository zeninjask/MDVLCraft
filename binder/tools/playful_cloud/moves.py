"""Playful Cloud moves: a few variants of every animation the weapon needs.

Grip (see cloud.py): each hand holds an end section like a sword; the middle one dangles between them.
Hand positions are relative to the pelvis, (right, up, forward) in blocks; the shoulders sit at (+-0.375, 0.63, 0)
and the arm reaches about 0.55.
"""
import math

